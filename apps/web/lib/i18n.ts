export const SUPPORTED_UI_LOCALES = [
  "auto", "en", "es", "fr", "de", "tr", "ja", "zh", "zh-TW", "ar",
] as const;

export const SUPPORTED_OUTPUT_LOCALES = [
  "auto", "en", "es", "fr", "de", "tr", "ja", "zh", "zh-TW", "ar",
] as const;

export type SupportedUiLocale = (typeof SUPPORTED_UI_LOCALES)[number];
export type SupportedOutputLocale = (typeof SUPPORTED_OUTPUT_LOCALES)[number];

/** Backward-compatible output-locale names for older callers. */
export const SUPPORTED_LOCALES = SUPPORTED_OUTPUT_LOCALES;
export type SupportedLocale = SupportedOutputLocale;

const RTL_LOCALES = new Set(["ar", "he", "fa", "ur"]);

function primaryTag(locale: string): string {
  return (locale.trim().replaceAll("_", "-").split("-")[0] || "en").toLowerCase();
}

/** Preserve Traditional/Simplified Chinese intent before short-tag fallback. */
export function normalizeLocaleTag(locale: string): string {
  const clean = locale.trim().replaceAll("_", "-");
  if (!clean) return "en";
  if (clean.toLowerCase() === "auto") return "auto";
  const parts = clean.split("-").filter(Boolean);
  const primary = (parts[0] ?? "en").toLowerCase();
  if (primary !== "zh") return primary;
  const rest = parts.slice(1).map((part) => part.toLowerCase());
  if (rest.includes("hant") || rest.some((part) => ["tw", "hk", "mo"].includes(part))) {
    return "zh-TW";
  }
  return "zh";
}

export function normalizeUiLocale(
  locale: string,
  fallback: SupportedUiLocale = "auto",
): SupportedUiLocale {
  const normalized = normalizeLocaleTag(locale);
  return (SUPPORTED_UI_LOCALES as readonly string[]).includes(normalized)
    ? normalized as SupportedUiLocale
    : fallback;
}

export function normalizeOutputLocale(
  locale: string,
  fallback: SupportedOutputLocale = "auto",
): SupportedOutputLocale {
  const normalized = normalizeLocaleTag(locale);
  return (SUPPORTED_OUTPUT_LOCALES as readonly string[]).includes(normalized)
    ? normalized as SupportedOutputLocale
    : fallback;
}

export function isRTL(locale: string): boolean {
  return RTL_LOCALES.has(primaryTag(locale));
}

export function detectLocale(): SupportedUiLocale {
  if (typeof navigator === "undefined") return "auto";
  return normalizeUiLocale(navigator.language || "en", "auto");
}

function resolvedUiTag(locale: string): string {
  const normalized = normalizeLocaleTag(locale);
  if (normalized !== "auto") return normalized;
  return typeof navigator !== "undefined"
    ? normalizeLocaleTag(navigator.language || "en")
    : "en";
}

export function getStrings(locale: string): LocaleStrings {
  const table = STRINGS[resolvedUiTag(locale)] ?? {};
  return { ...en, ...table };
}

export function resolveOutputLocale(locale: string): string {
  if (locale === "auto") {
    return typeof navigator !== "undefined"
      ? normalizeLocaleTag(navigator.language || "en")
      : "en";
  }
  return normalizeLocaleTag(locale);
}

export function formatUi(
  template: string,
  values: Record<string, string | number>,
): string {
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function localeDisplayName(locale: SupportedUiLocale | SupportedOutputLocale, t: LocaleStrings): string {
  const names: Record<SupportedUiLocale, string> = {
    auto: t.languageAuto,
    en: t.localeEnglish,
    es: t.localeSpanish,
    fr: t.localeFrench,
    de: t.localeGerman,
    tr: t.localeTurkish,
    ja: t.localeJapanese,
    zh: t.localeChineseSimplified,
    "zh-TW": t.localeChineseTraditional,
    ar: t.localeArabic,
  };
  return names[locale];
}

function flag(raw: string | undefined): boolean {
  return ["1", "true", "yes", "on"].includes((raw ?? "").trim().toLowerCase());
}

export function defaultUiLocale(env: Record<string, string | undefined> = process.env): SupportedUiLocale {
  const profileDefault = flag(env.NEXT_PUBLIC_NAS_SLIM) ? "zh-TW" : "en";
  return normalizeUiLocale(env.NEXT_PUBLIC_DEFAULT_UI_LOCALE ?? profileDefault, profileDefault);
}

// Next.js only inlines NEXT_PUBLIC_* references when each key is accessed
// directly. Passing the dynamic process.env object made the client bundle fall
// back to English while the NAS server rendered zh-TW, causing hydration text
// mismatches in a real browser.
export const DEFAULT_UI_LOCALE = defaultUiLocale({
  NEXT_PUBLIC_NAS_SLIM: process.env.NEXT_PUBLIC_NAS_SLIM,
  NEXT_PUBLIC_DEFAULT_UI_LOCALE: process.env.NEXT_PUBLIC_DEFAULT_UI_LOCALE,
});

export function localizeGenerationError(message: string, t: LocaleStrings): string {
  const value = message.toLowerCase();
  if (value.includes("generation cap reached") || value.includes("openflipbook_usage_cap_reached")) {
    return t.generationCapReached;
  }
  if (value.includes("cooling down") || value.includes("openclaw_circuit_open")) {
    const seconds = /(?:about |after |retry[_ ]after[_ ]seconds[^0-9]*)?(\d+)s?/i.exec(message)?.[1] ?? "0";
    return formatUi(t.circuitCoolingDown, { seconds });
  }
  if (value.includes("declined this one") || value.includes("returned no images")) return t.imageModelDeclined;
  if (value.includes("too long") || value.includes("timed out") || value.includes("timeout")) return t.generationTimedOut;
  if (value.includes("busy right now") || value.includes("rate limit")) return t.imageServiceBusy;
  if (value.includes("safety filter") || value.includes("content_policy") || value.includes("moderation")) return t.safetyBlocked;
  if (value.includes("generation failed") || value.includes("upstream returned")) return t.generationFailedRetry;
  return t.generationFailedRetry;
}
